"""Unit tests for cross-source reconciliation tables and generated Markdown report."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from cleanpulse.silver.reconcile import run_reconciliation


def test_run_reconciliation_generates_tables_and_report(tmp_path: Path) -> None:
    silver_dir = tmp_path / "silver"
    silver_dir.mkdir(parents=True, exist_ok=True)

    pd.DataFrame(
        {
            "report_date": ["2022-01-05", "2022-01-06", "2023-02-01"],
            "division": ["Dhaka", "Dhaka", "Dhaka"],
            "cases": [10, 20, 50],
            "source_label": ["sec", "sec", "sec"],
        }
    ).to_parquet(silver_dir / "dengue_division_daily.parquet", index=False)

    pd.DataFrame(
        {
            "division": ["Dhaka", "Dhaka"],
            "year": [2022, 2023],
            "month": [1, 2],
            "infected": [30, 48],
            "death": [1, 2],
        }
    ).to_parquet(silver_dir / "dengue_division_monthly_b.parquet", index=False)

    ref_csv = tmp_path / "ref.csv"
    pd.DataFrame(
        {
            "year": [2022, 2023],
            "cases": [30, 50],
            "deaths": [1, 2],
            "scope_note": ["Jan 1-Dec 31", "Full year"],
            "source_outlet": ["Outlet1", "Outlet2"],
            "source_url": ["https://example.com/1", "https://example.com/2"],
            "accessed_utc": ["2026-11-15", "2026-11-15"],
            "verified_on_page": [True, True],
        }
    ).to_csv(ref_csv, index=False)

    report_md = tmp_path / "reconciliation_report.md"
    outputs = run_reconciliation(
        silver_dir=silver_dir,
        reference_csv=ref_csv,
        report_path=report_md,
    )

    a_ref = pd.read_parquet(outputs.a_vs_ref_path)
    b_ref = pd.read_parquet(outputs.b_vs_ref_path)
    a_vs_b = pd.read_parquet(outputs.a_monthly_vs_b_path)

    assert len(a_ref) == 2
    assert list(a_ref["abs_diff"]) == [0, 0]
    assert len(b_ref) == 2
    assert len(a_vs_b) == 2
    assert report_md.exists()
    content = report_md.read_text(encoding="utf-8")
    assert "Generated by cleanpulse reconcile-sources" in content
    assert "Exact matches:** 1/2 (50.00%)" in content
