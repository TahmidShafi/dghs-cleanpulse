"""Independent replication of docs/analysis_plan.md (Phase 2, DGHS-CleanPulse).

Written from the plan text only, without reference to the pipeline's gold code.
Reads the silver Parquet tables and gold lag table, verifies parity, and writes
``docs/replication_check.md``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

VARIABLES = {
    "weekly_precip_mm": ("precipitation_sum", "sum"),
    "weekly_temp_c": ("temperature_2m_mean", "mean"),
    "weekly_humidity_pct": ("relative_humidity_2m_mean", "mean"),
}
LAGS = range(0, 9)


def spearman(x: np.ndarray, y: np.ndarray) -> float | None:
    """Spearman rho = Pearson correlation of average ranks; None if either series is constant."""
    rx = pd.Series(x).rank(method="average").to_numpy()
    ry = pd.Series(y).rank(method="average").to_numpy()
    if np.std(rx) == 0 or np.std(ry) == 0:
        return None
    return float(np.corrcoef(rx, ry)[0, 1])


def weekly_table(dengue: pd.DataFrame, weather: pd.DataFrame) -> pd.DataFrame:
    d = dengue.copy()
    d["date"] = pd.to_datetime(d["report_date"]) - pd.Timedelta(days=1)  # effective_date
    nat = d.groupby("date", as_index=False)["cases"].sum().assign(division="National")
    d = pd.concat([d[["division", "date", "cases"]], nat], ignore_index=True)
    d = d.rename(columns={"division": "scope"})

    w = weather.copy()
    w["date"] = pd.to_datetime(w["date"])
    daily = d.merge(w, on=["scope", "date"], how="inner")  # both cases and weather present

    iso = daily["date"].dt.isocalendar()
    daily["iso_year"], daily["iso_week"] = iso["year"], iso["week"]
    agg = {"cases": "sum", "date": ["min", "count"]}
    for _, (col, how) in VARIABLES.items():
        agg[col] = how
    wk = daily.groupby(["scope", "iso_year", "iso_week"]).agg(agg)
    wk.columns = ["weekly_cases", "week_start", "days"] + list(VARIABLES)
    wk = wk.reset_index()
    wk = wk[wk["days"] == 7].sort_values(["scope", "week_start"])
    return wk


def correlations(wk: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for scope, g in wk.groupby("scope"):
        g = g.sort_values("week_start").reset_index(drop=True)
        # contiguity check: consecutive Mondays only
        gaps = g["week_start"].diff().dropna().dt.days
        assert (gaps == 7).all(), f"non-contiguous weeks in {scope}"
        cases = g["weekly_cases"].to_numpy(dtype=float)
        dlog = np.diff(np.log(cases + 1))
        for var in VARIABLES:
            x = g[var].to_numpy(dtype=float)
            dx = np.diff(x)
            for k in LAGS:
                # raw: cases_t with X_{t-k}
                yr, xr = cases[k:], x[: len(x) - k]
                rows.append((scope, var, "raw", k, spearman(xr, yr), len(yr)))
                # differenced: dlog_t with dX_{t-k}
                yd, xd = dlog[k:], dx[: len(dx) - k]
                rows.append((scope, var, "diff_log", k, spearman(xd, yd), len(yd)))
    return pd.DataFrame(
        rows,
        columns=["scope", "variable", "transform", "lag_weeks", "rho_mine", "n_mine"],
    )


def main() -> None:
    repo_root = Path(__file__).resolve().parents[2]
    dengue = pd.read_parquet(repo_root / "data" / "silver" / "dengue_division_daily.parquet")
    weather = pd.read_parquet(repo_root / "data" / "silver" / "weather_divisions_daily.parquet")
    theirs = pd.read_parquet(repo_root / "data" / "gold" / "lag_correlations_weekly.parquet")

    wk = weekly_table(dengue, weather)
    mine = correlations(wk)
    m = mine.merge(
        theirs,
        on=["scope", "variable", "transform", "lag_weeks"],
        how="outer",
        indicator=True,
    )
    both = m[m["_merge"] == "both"].copy()
    both["n_match"] = both["n_mine"] == both["n"]
    both["abs_diff"] = (both["rho_mine"] - both["rho"]).abs()

    joined_count = int((m["_merge"] == "both").sum())
    n_mismatches = int((~both["n_match"]).sum())
    null_mine = int(both["rho_mine"].isna().sum())
    null_theirs = int(both["rho"].isna().sum())
    max_abs_diff = float(both["abs_diff"].max())
    worst = both.sort_values("abs_diff", ascending=False).head(3)
    if max_abs_diff <= 1e-9:
        precision_note = "Replication and gold agree to floating-point precision."
    else:
        precision_note = (
            "Residual differences arise from floating-point near-ties in rank assignment "
            "(values equal in exact arithmetic but differing at ~1e-13 due to summation order); "
            "rho is therefore displayed to 2 decimals."
        )

    lines = [
        "# Independent Replication Check",
        "",
        "<!-- Generated by backend/scripts/replicate_analysis.py — do not edit by hand -->",
        "",
        "## Summary",
        "",
        (
            f"- **Rows compared (replication / gold / joined):** "
            f"{len(mine)} / {len(theirs)} / {joined_count}"
        ),
        f"- **Sample size (`n`) mismatches:** {n_mismatches}",
        f"- **Null `rho` counts (replication / gold):** {null_mine} / {null_theirs}",
        f"- **Max `|delta rho|`:** `{max_abs_diff:.3e}`",
        "",
        precision_note,
        "",
        "## 3 Largest `|delta rho|` Differences",
        "",
        (
            "| Scope | Variable | Transform | Lag (weeks) "
            "| `rho_replication` | `rho_gold` | `|delta rho|` |"
        ),
        "|---|---|---|---:|---:|---:|---:|",
    ]
    for _, row in worst.iterrows():
        lines.append(
            f"| {row['scope']} | `{row['variable']}` | `{row['transform']}` | "
            f"{int(row['lag_weeks'])} | {row['rho_mine']:.6f} | {row['rho']:.6f} | "
            f"{row['abs_diff']:.3e} |"
        )
    lines.append("")

    out_path = repo_root / "docs" / "replication_check.md"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({joined_count} rows compared, max |delta rho| = {max_abs_diff:.3e})")


if __name__ == "__main__":
    main()
